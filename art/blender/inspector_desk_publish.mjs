// The Inspector's Desk scenes (inspector_scene.py → .artifacts/inspector-desk/scene)
// into the game: public/assets/images/InspectorDesk/v<version>/ as WebP, and
// src/ui/styles/inspector-desk-geometry.css — each picture's shape and, for
// each sheet a page is laid on, its centre, size and turn, as custom
// properties, for inspector-desk.css to lay the pages over the paper.
//
//   node art/blender/inspector_desk_publish.mjs [version]
import { createRequire } from "node:module";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
const require = createRequire(new URL("../../package.json", import.meta.url));
const sharp = require("sharp");
sharp.cache(false);
const path = (rel) => decodeURIComponent(new URL(`../../${rel}`, import.meta.url).pathname).replace(/^\/(\w:)/, "$1");
const VERSION = process.argv[2] ?? "2";
const IN = (name) => path(`.artifacts/inspector-desk/scene/${name}`);
const OUT = path(`public/assets/images/InspectorDesk/v${VERSION}`);
mkdirSync(OUT, { recursive: true });

// name, its key in the CSS, the width it is published at
const scenes = [["casefile", "file", 2400], ["notebook", "book", 2000], ["settings", "set", 2880]];
const pct = (v) => `${(v * 100).toFixed(3)}%`;
const lines = [];
for (const [name, key, width] of scenes) {
  if (!existsSync(IN(`${name}.png`))) continue;
  await sharp(IN(`${name}.png`)).resize({ width, withoutEnlargement: true }).webp({ quality: 88, alphaQuality: 100, effort: 6 }).toFile(`${OUT}/${name}.webp`);
  const g = JSON.parse(readFileSync(IN(`${name}.json`), "utf8"));
  lines.push(`  --${key}-art: url('/assets/images/InspectorDesk/v${VERSION}/${name}.webp');`, `  --${key}-ratio: ${g.width} / ${g.height};`);
  for (const [page, p] of Object.entries(g.pages)) {
    lines.push(`  --${key}-${page}-x: ${pct(p.x)}; --${key}-${page}-y: ${pct(p.y)}; --${key}-${page}-w: ${pct(p.w)}; --${key}-${page}-h: ${pct(p.h)}; --${key}-${page}-turn: ${p.turn}deg;`);
  }
  console.log(name);
}
writeFileSync(path("src/ui/styles/inspector-desk-geometry.css"),
  `/* Generated by art/blender/inspector_desk_publish.mjs: the shape of each of\n   the Inspector's Desk scenes, and for each sheet a page lies on its centre,\n   size (fractions of the picture) and turn. Render again, publish again; do\n   not edit. */\n:root {\n${lines.join("\n")}\n}\n`);
console.log("geometry written");
